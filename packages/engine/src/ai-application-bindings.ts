export function unsupportedRouteMessage(payload: unknown): string {
  const value = unsupportedRouteSchema.parse(payload);
  const messages = {
    "unsupported-scenario": "This scenario needs review before the return can be calculated. Check the support details and provide the required source facts.",
    "missing-facts": "Some required source facts are missing. Check the original documents and complete the unresolved interview items.",
    "conflicting-sources": "The supplied sources conflict. Resolve the difference using the original documents before relying on a calculation.",
    "missing-verified-audit": "A current verified calculation is needed to explain these amounts. Confirm the source facts and calculate the supported return first.",
    "privacy-boundary": "These private details cannot be inferred from the supplied material. Confirm the actual source identity locally in the interview.",
  } as const;
  return messages[value.reasonCode];
}
