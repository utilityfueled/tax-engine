export function applicationSchemaForTask(task: AiTask): z.ZodType<ApplicationTaskOutput> { return schemas[task]; }
export type ApplicationTaskOutput = z.infer<(typeof schemas)[AiTask]>;
export interface ApplicationTaxContext {
  taxYear: number; ruleVersion: string;
  excerpts: Array<{ id: string; taxYear: number; text: string }>;
  auditEntries: Array<{ id: string; taxYear: number; value: string; explanation: string }>;
}
export interface ApplicationGroundingContext {
  sources: readonly { id: string; text: string }[];
  requestedFields?: readonly { name: string; kind: "money" | "date" | "text" }[];
  taxContext?: ApplicationTaxContext;
}
const numeric = /^-?\d+(?:\.\d+)?$/;
function sourceAmounts(text: string): string[] {
  // Parentheses and explicit minus signs are part of the value, never discarded.
  return [...text.matchAll(/(?:\(\s*\$?\s*|[-+]?\s*\$?\s*)(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?\s*\)?/g)].map(match => {
    const value = match[0].trim(); const plain = value.replace(/[$,()\s]/g, "");
    return value.startsWith("(") ? `-${plain}` : plain;
  });
}
function hasMoney(text: string, value: string) {
  return numeric.test(value) && sourceAmounts(text).some(item => new Money(item).eq(value));
}
export function validateApplicationSuggestions(value: unknown, redactedText: string): void {
  if (!value || typeof value !== "object" || !("suggestions" in value)) return;
  const rows = z.array(documentSuggestionSchema.passthrough()).parse(value.suggestions);
  const seen = new Set<string>();
  for (const row of rows) {
    if (!redactedText.includes(row.sourceQuote) || !row.sourceQuote.includes(row.description)
      || (row.date && !row.sourceQuote.includes(row.date))) throw new Error("Document fields lack a literal source quote.");
    if (!hasMoney(row.sourceQuote, row.amount)) throw new Error("Amount is absent from the quoted source.");
    const key = JSON.stringify([row.date, row.description, new Money(row.amount).toFixed()]);
    if (seen.has(key)) throw new Error("Duplicate document suggestion requires reconciliation.");
    seen.add(key);
  }
}
export function validateApplicationTaxContext(context?: ApplicationTaxContext): boolean {
  if (!context) return false;
  if (!Number.isSafeInteger(context.taxYear) || !context.ruleVersion.trim() || !context.excerpts.length || !context.auditEntries.length) throw new Error("Verified year-specific source and audit context is required.");
  const entries = [...context.excerpts, ...context.auditEntries];
  if (entries.some(entry => !entry.id || entry.taxYear !== context.taxYear) || new Set(entries.map(entry => entry.id)).size !== entries.length) throw new Error("Verified context has conflicting years or source identity.");
  if (context.excerpts.some(entry => !entry.text.trim()) || context.auditEntries.some(entry => !numeric.test(entry.value) || !new Money(entry.value).isFinite())) throw new Error("Verified source or audit content is incomplete.");
  return true;
}
export function parseApplicationTaskOutput(task: AiTask, payload: unknown, context: ApplicationGroundingContext): ApplicationTaskOutput {
  let value = applicationSchemaForTask(task).parse(payload);
  if (!context.sources.length || context.sources.some(source => !source.id || !source.text.trim())) throw new Error("Actual source context is required.");
  if (new Set(context.sources.map(source => source.id)).size !== context.sources.length) throw new Error("Duplicate source identity.");
  const tax = context.taxContext;
  if (AI_TASKS[task].requiresVerifiedTaxContext && !validateApplicationTaxContext(tax)) throw new Error("Verified source and audit context is required.");
  const permitted = new Set([...context.sources.map(source => source.id), ...(tax?.excerpts.map(item => item.id) ?? []), ...(tax?.auditEntries.map(item => item.id) ?? [])]);
  if (value.sourceIds.some(id => !permitted.has(id)) || new Set(value.sourceIds).size !== value.sourceIds.length) throw new Error("Invalid source citation.");
  if (/ready (?:to|for) (?:download|fil(?:e|ing))|filing[- ]ready|guaranteed (?:refund|deduction)/i.test(JSON.stringify(value))) throw new Error("Invented readiness claim.");
  if ("facts" in value) {
    if (new Set(value.facts.map(fact => fact.name)).size !== value.facts.length) throw new Error("Duplicate source fact.");
    for (const fact of value.facts) {
      const source = context.sources.find(source => source.id === fact.sourceId);
      if (!source || !value.sourceIds.includes(fact.sourceId)) throw new Error("Fact has no cited source.");
      const requested = context.requestedFields?.find(field => field.name === fact.name);
      if (context.requestedFields && (!requested || requested.kind !== fact.kind)) throw new Error("Fact does not match the requested field contract.");
      if (fact.value === null) {
        if (fact.sourceQuote !== null && !source.text.includes(fact.sourceQuote)) throw new Error("Unknown fact has an invented quote.");
        continue;
      }
      if (!fact.sourceQuote || !source.text.includes(fact.sourceQuote)) throw new Error("Known fact requires a literal source quote.");
      if (fact.kind === "money" && !hasMoney(fact.sourceQuote, fact.value)) throw new Error("Monetary fact differs from its source.");
      if (fact.kind === "date" && (!z.iso.date().safeParse(fact.value).success || !fact.sourceQuote.includes(fact.value))) throw new Error("Date is not unambiguously stated in its source.");
      if (fact.kind === "text" && (!fact.value.trim() || !fact.sourceQuote.includes(fact.value))) throw new Error("Text fact is not literally stated in its source.");
    }
  }
  if (value.disposition === "abstain" && (("suggestions" in value && value.suggestions.length)
    || ("facts" in value && value.facts.some(fact => fact.value !== null)) || ("engineValues" in value && value.engineValues.length))) throw new Error("Abstention cannot carry actionable output.");
  validateApplicationSuggestions(value, context.sources.map(source => source.text).join("\n"));
  if ("engineValues" in value && value.disposition === "answer") {
    if (!value.sourceIds.some(id => tax?.excerpts.some(item => item.id === id))
      || !value.sourceIds.some(id => tax?.auditEntries.some(item => item.id === id))) throw new Error("Both source and audit citations are required.");
    if (new Set(value.engineValues.map(item => item.id)).size !== value.engineValues.length) throw new Error("Duplicate audit value.");
    for (const entry of value.engineValues) {
      const actual = tax?.auditEntries.find(item => item.id === entry.id);
      if (!actual || !new Money(actual.value).eq(entry.value) || !value.sourceIds.includes(entry.id)) throw new Error("Changed or uncited audit value.");
    }
    const text = "answer" in value ? value.answer : value.summary;
    for (const amount of text.match(/(?:\$|USD\s*)[-+]?\d[\d,]*(?:\.\d+)?/g) ?? []) {
      const amountValue = amount.replace(/USD|\$|,|\s/g, "");
      if (!tax?.auditEntries.some(item => new Money(item.value).eq(amountValue))) throw new Error("Unverified monetary claim.");
    }
    const allowedNumbers = [String(tax?.taxYear), ...(tax?.auditEntries.map(item => item.value) ?? []),
      ...("facts" in value ? value.facts.flatMap(fact => fact.kind === "money" && fact.value !== null ? [fact.value] : []) : [])];
    for (const token of text.match(/(?<![\w])[-+]?\d[\d,]*(?:\.\d+)?/g) ?? []) {
      if (!allowedNumbers.some(number => numeric.test(number) && new Money(number).eq(token.replaceAll(",", "")))) throw new Error("Unverified numeric audit claim.");
    }
  }
  if (task === "expense-categorization") {
    const expense = documentExpenseSchema.parse(value);
    value = { ...expense, suggestions: expense.suggestions.map(row => ({ ...row, confidence: "low" as const,
      suggestedBusinessUse: false, suggestedCategory: row.suggestedCategory === "not-business" ? "not-business" as const : "needs-review" as const })) };
  }
  return value;
}
/** Derived only from the real parsed application value; there is no model-authored sidecar. */
export function normalizeApplicationTaskOutput(task: AiTask, payload: unknown) {
  const value = applicationSchemaForTask(task).parse(payload);
  const fields = "facts" in value ? Object.fromEntries(value.facts.flatMap(fact => fact.value === null ? [] : [[fact.name, fact.value]]))
    : task === "document-classification" && "documentType" in value && value.disposition === "answer" ? { documentType: value.documentType } : {};
  return { disposition: value.disposition, fields, category: "reviewCategory" in value ? value.reviewCategory : null,
    sourceIds: value.sourceIds, engineValues: "engineValues" in value ? Object.fromEntries(value.engineValues.map(item => [item.id, item.value])) : {},
    filingReady: /ready (?:to|for) (?:download|fil(?:e|ing))|filing[- ]ready|guaranteed (?:refund|deduction)/i.test(JSON.stringify(value)) };
}
