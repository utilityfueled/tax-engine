import { describe, expect, it } from "vitest";
import { rateLimitTiers } from "@/lib/rate-limit";
import { isValidHostedDocumentId } from "@/lib/hosted-workspace-route";

describe("hosted upload guards", () => {
  it("accepts document ids generated by workspace ingestion", () => {
    expect(isValidHostedDocumentId("unknown:invoice.pdf:18273")).toBe(true);
    expect(isValidHostedDocumentId("1099-nec:Contractor Copy.pdf:28491#1")).toBe(true);
    expect(isValidHostedDocumentId("w2:Acme Payroll.pdf:40211")).toBe(true);
    expect(isValidHostedDocumentId("unknown:Northwind Invoice (Mar, 2026).pdf:40211")).toBe(true);
    expect(isValidHostedDocumentId("unknown:Cliente — Factura #7.pdf:40211")).toBe(true);
  });

  it("still rejects obviously unsafe document ids", () => {
    expect(isValidHostedDocumentId("")).toBe(false);
    expect(isValidHostedDocumentId("../../../etc/passwd")).toBe(false);
    expect(isValidHostedDocumentId("invoice\t2025.pdf")).toBe(false);
  });

  it("allows normal multi-file hosted batches without the old low ceiling", () => {
    expect(rateLimitTiers.upload).toEqual({
      maxRequests: 240,
      windowMs: 60 * 1000
    });
  });
});
