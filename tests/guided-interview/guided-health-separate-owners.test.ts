// Spec: spec/federal/marketplace-health-separate-owners.yaml.
import { expect, it } from "vitest";
import { buildTaxInputFromGuidedData } from "@/lib/guided-interview-bridge";
import { healthInsuranceSourceErrors } from "@/lib/guided-health-insurance-facts";
import { validateSection, updateSectionData } from "@/lib/guided-interview-flow";
import { calculateFederalTax } from "@/engine/federal";
import { TaxYearInputSchema } from "@/models/inputs";
import { guidedMarketplaceHealthSeparateOwnersState } from "../fixtures/guided-marketplace-health-separate-owners";

it("retains three actual source plans through invalidation and reconfirmation", () => {
  const state = guidedMarketplaceHealthSeparateOwnersState();
  expect(healthInsuranceSourceErrors(state)).toEqual({});
  expect(validateSection(state, "adjustments").status).toBe("complete");
  expect(validateSection(state, "credits").status).toBe("complete");
  const input = buildTaxInputFromGuidedData(state);
  expect(input?.w2s.map(row => [row.accountHolder, row.wages, row.medicareWages])).toEqual([["primary", "46000", "40000"], ["spouse", "43000", "40000"], ["primary", "12400", "10000"]]);
  expect(input?.form7206?.plans?.map(row => [row.businessSourceId, row.accountHolder, row.marketplaceCoverage])).toEqual([["formW2:0", "primary", true], ["formW2:1", "spouse", true], ["formW2:2", "primary", false]]);
  expect(calculateFederalTax(TaxYearInputSchema.parse(input)).schedule1?.seHealthInsurance.toFixed()).toBe("7050");
  const actualStatement = structuredClone(state.sectionData["income-w2"]);
  if (!actualStatement?.entries[2]) throw new Error("Missing original third employer statement");
  actualStatement.entries[2].wages = "12400.01";
  const withStatement = updateSectionData(state, "income-w2", actualStatement);
  const adjustments = structuredClone(state.sectionData.adjustments);
  const paid = adjustments?.healthInsuranceFacts?.plans[2]?.payments[0];
  if (!adjustments || !paid) throw new Error("Missing original separate plan");
  paid.grossPremium = paid.ownerOrBusinessPaid = paid.personAmounts[0].amountPaid = "200.01";
  const edited = updateSectionData(withStatement, "adjustments", adjustments);
  expect(edited.sectionData.adjustments?.healthInsuranceFacts?.sourceFactsConfirmed).toBeNull();
  expect(edited.sectionData.adjustments?.healthInsuranceFacts?.marketplaceCreditAllocation?.sourceFactsConfirmed).toBeNull();
  expect(edited.sectionData.credits?.premiumTaxCredit?.sourceFactsConfirmed).toBeNull();
  expect(edited.sectionData.payments?.estimatedTaxFacts?.sourceFactsConfirmed).toBeNull();
  expect(buildTaxInputFromGuidedData(edited)).toBeNull();
  const actual = structuredClone(edited.sectionData.adjustments);
  if (!actual?.healthInsuranceFacts) throw new Error("Missing original source packet");
  actual.healthInsuranceFacts.sourceFactsConfirmed = true;
  const rootOnly = updateSectionData(edited, "adjustments", actual);
  expect(buildTaxInputFromGuidedData(rootOnly)).toBeNull();
  if (!actual.healthInsuranceFacts.marketplaceCreditAllocation) throw new Error("Missing original recorded credit choice");
  actual.healthInsuranceFacts.marketplaceCreditAllocation.sourceFactsConfirmed = true;
  const confirmed = updateSectionData(rootOnly, "adjustments", actual);
  expect(buildTaxInputFromGuidedData(confirmed)).toBeNull();
  const credits = structuredClone(confirmed.sectionData.credits);
  if (!credits?.premiumTaxCredit) throw new Error("Missing original Marketplace sources");
  credits.premiumTaxCredit.sourceFactsConfirmed = true;
  const coverageConfirmed = updateSectionData(confirmed, "credits", credits);
  expect(buildTaxInputFromGuidedData(coverageConfirmed)).toBeNull();
  const payments = structuredClone(coverageConfirmed.sectionData.payments);
  if (!payments?.estimatedTaxFacts) throw new Error("Missing original payment sources");
  payments.estimatedTaxFacts.sourceFactsConfirmed = true;
  const fullyConfirmed = updateSectionData(coverageConfirmed, "payments", payments);
  const reloaded = JSON.parse(JSON.stringify(fullyConfirmed)) as typeof state;
  const rebuilt = buildTaxInputFromGuidedData(reloaded);
  expect(rebuilt?.form7206?.plans?.[2]?.payments?.[0]?.grossPremium).toBe("200.01");
  expect(rebuilt?.w2s[2].wages).toBe("12400.01");
  expect(calculateFederalTax(TaxYearInputSchema.parse(rebuilt)).schedule1?.seHealthInsurance.toFixed()).toBe("7050");
});
